#!/usr/bin/env python3
"""Generate templates.hpp: embedded glyph bitmaps for the C++ fusion OCR.

Renders A-Z0-9 in DejaVuSans-Bold and LiberationSans-Bold, binarizes at
height 64, and emits them as a C++ array of {w,h,bits} structs.
"""
import numpy as np
from PIL import Image, ImageDraw, ImageFont

FONTS = [
    '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',
    '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf',
]
CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'

out = []
out.append('// AUTO-GENERATED by scripts/gen_templates.py — do not edit.')
out.append('// Binary glyph masks (1 = ink) for template-matching OCR,')
out.append('// rendered from DejaVuSans-Bold and LiberationSans-Bold at 64 px.')
out.append('#ifndef PLATE_READER__TEMPLATES_HPP_')
out.append('#define PLATE_READER__TEMPLATES_HPP_')
out.append('')
out.append('#include <array>')
out.append('#include <cstdint>')
out.append('#include <vector>')
out.append('')
out.append('namespace plate_reader {')
out.append('')
out.append('struct GlyphTemplate')
out.append('{')
out.append('  int w;')
out.append('  int h;')
out.append('  std::vector<uint8_t> mask;  // w*h, 1 = ink')
out.append('};')
out.append('')
out.append('// 2 fonts x 36 chars, index = font*36 + char')
out.append('inline const std::vector<GlyphTemplate> & glyph_templates()')
out.append('{')

blocks = []
for fp in FONTS:
    f = ImageFont.truetype(fp, 64)
    for ch in CHARS:
        im = Image.new('L', (96, 96), 0)
        ImageDraw.Draw(im).text((14, 6), ch, font=f, fill=255)
        a = np.array(im)
        ys, xs = np.where(a > 40)
        tt = (a[ys.min():ys.max() + 1, xs.min():xs.max() + 1] > 127).astype(np.uint8)
        h, w = tt.shape
        bits = ','.join(str(int(v)) for v in tt.flatten())
        blocks.append((ch, w, h, bits))

out.append('  static const std::vector<GlyphTemplate> T = {')
for ch, w, h, bits in blocks:
    vals = bits.split(',')
    lines = []
    for i in range(0, len(vals), 24):
        lines.append('      ' + ','.join(vals[i:i + 24]) + ',')
    out.append(f'    {{{w}, {h}, std::vector<uint8_t>{{')
    out.extend(lines)
    out.append('    }},')
out.append('  };')
out.append('  return T;')
out.append('}')
out.append('')
out.append('}  // namespace plate_reader')
out.append('')
out.append('#endif  // PLATE_READER__TEMPLATES_HPP_')
out.append('')

with open('/home/z/my-project/download/plate_reader/include/plate_reader/templates.hpp', 'w') as fh:
    fh.write('\n'.join(out))
print('wrote templates.hpp,', len(blocks), 'glyphs')
